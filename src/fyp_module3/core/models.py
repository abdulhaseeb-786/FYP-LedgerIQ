"""Data contracts, schemas, and upstream/downstream interfaces for FYP-Module-3."""

from __future__ import annotations

from typing import List, Optional, Literal
from pydantic import BaseModel, Field


class StandardizedAccountRecord(BaseModel):
    """Normalized ledger account record."""
    account_code: Optional[str] = None
    account_name: str
    debit: float = 0.0
    credit: float = 0.0
    net_balance: float = 0.0
    line_item_id: Optional[str] = None
    note_number: Optional[int] = None
    confidence: float = 1.0
    is_adjusted: bool = False
    adjustment_reason: Optional[str] = None
    # 1-based row of this account in the SOURCE worksheet, for traceability.
    tb_row_index: Optional[int] = None
    # How the classifier reached line_item_id; "default" means it was a fallback
    # guess rather than a recognised account title.
    classification_source: str = "exact"
    # Set when a heuristic moved the balance to the other side, which makes any
    # classification taken before the move stale.
    side_changed: bool = False


class UpstreamModulePayload(BaseModel):
    """Contract emitted by upstream modules (Module 7 OCR / Module 1 Normalizer) as per Section 8."""
    client_id: str = "Client_Default"
    period_ended: str = "June 30, 2025"
    accounts: List[StandardizedAccountRecord]
    is_balanced: bool = True
    delta: float = 0.0
    audit_notes: List[str] = Field(default_factory=list)
    # Ingestion statistics, measured by the parser rather than inferred later.
    total_raw_rows: int = 0
    junk_rows_skipped: int = 0
    error_cells_detected: int = 0
    skipped_row_labels: List[str] = Field(default_factory=list)
    source_sheet: Optional[str] = None


class ClassificationResult(BaseModel):
    """Account classification output."""
    account_name: str
    line_item_id: str
    statement: Literal["SOFP", "PL"]
    section: str
    label: str
    note_number: Optional[int] = None
    confidence: float
    source: Literal["exact", "fuzzy", "heuristic", "manual", "default"] = "exact"
    # Set only when `source` is "default": why nothing matched.
    unclassified_reason: Optional[str] = None


class AuditEntry(BaseModel):
    """Audit entry recording balancing and mapping adjustments."""
    account_name: str
    account_code: Optional[str] = None
    action: str
    before_dr: float
    before_cr: float
    after_dr: float
    after_cr: float
    delta: float
    heuristic: str
    explanation: str


class NoteItem(BaseModel):
    """A sub-item line in a statutory disclosure note."""
    account_code: Optional[str] = None
    account_name: str
    amount: float
    line_item_id: Optional[str] = None
    # Row in the SOURCE worksheet this account was ingested from.
    tb_row_index: Optional[int] = None
    # Row on the exported TB worksheet, which the note formula points at.
    tb_sheet_row: Optional[int] = None


class CompiledNote(BaseModel):
    """A synthesized statutory disclosure note schedule."""
    note_number: int
    title: str
    target_statement: Literal["SOFP", "PL"]
    target_line_id: str
    items: List[NoteItem] = Field(default_factory=list)
    start_row: Optional[int] = None
    subtotal_row: Optional[int] = None
    subtotal_cell_ref: Optional[str] = None  # e.g., "Notes!D22"


class VerificationReport(BaseModel):
    """Report generated by the Statements Verification & Self-Correction Engine."""
    is_tb_balanced: bool = True
    tb_delta: float = 0.0
    is_bs_balanced: bool = True
    bs_delta: float = 0.0
    total_assets: float = 0.0
    total_liabilities_and_equity: float = 0.0
    total_equity: float = 0.0
    total_non_current_liabilities: float = 0.0
    total_current_liabilities: float = 0.0
    net_profit: float = 0.0
    zero_leakage_passed: bool = True
    unassigned_accounts: List[str] = Field(default_factory=list)
    retries_attempted: int = 0
    auto_corrections: List[str] = Field(default_factory=list)
    status_message: str = ""
    # Note subtotals must equal the face lines they support, because the
    # exported workbook links the face line to the note cell.
    notes_reconciled: bool = True
    note_mismatches: List[str] = Field(default_factory=list)
    # Accounts carrying a line_item_id that no statement actually renders.
    unrendered_accounts: List[str] = Field(default_factory=list)
    # Set when the balancer inserted a fabricated plug to force parity.
    contains_balancing_plug: bool = False
    plug_amount: float = 0.0


class DataQualityIssue(BaseModel):
    """An issue identified during pre-flight data quality analysis."""
    severity: Literal["INFO", "WARNING", "CRITICAL"]
    category: str
    description: str
    remediation_hint: str
    row_or_account: Optional[str] = None


class DataHealthReport(BaseModel):
    """Pre-flight quality assessment of raw input trial balance."""
    is_processable: bool = True
    health_score: float = 100.0  # 0 to 100
    severity: Literal["CLEAN", "WARNING_RECOVERABLE", "CRITICAL_UNPROCESSABLE"] = "CLEAN"
    headline: str = "Data structure valid and ready for processing."
    issues: List[DataQualityIssue] = Field(default_factory=list)
    total_raw_rows: int = 0
    valid_accounts_count: int = 0
    junk_rows_skipped: int = 0
    average_classifier_confidence: float = 1.0
    initial_dr: float = 0.0
    initial_cr: float = 0.0
    initial_delta: float = 0.0
    imbalance_percentage: float = 0.0


class WorkbookAuditResult(BaseModel):
    """Result of evaluating the FORMULAS actually written into the workbook."""
    passed: bool = True
    checks: List[str] = Field(default_factory=list)
    failures: List[str] = Field(default_factory=list)
    balance_sheet_variance: float = 0.0
    cash_flow_variance: float = 0.0
    equity_variance: float = 0.0
    trial_balance_variance: float = 0.0


class DesktopPipelineResult(BaseModel):
    """Unified API response for desktop app integration."""
    status: Literal["SUCCESS", "RECOVERED_WARNING", "FAILED_CRITICAL"]
    message: str
    is_balanced: bool = True
    health_report: DataHealthReport
    verification_report: Optional[VerificationReport] = None
    workbook_audit: Optional[WorkbookAuditResult] = None
    output_file: Optional[str] = None
    audit_trail: List[AuditEntry] = Field(default_factory=list)


